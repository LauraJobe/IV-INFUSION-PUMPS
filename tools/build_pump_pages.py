"""Write single-pump pages (e.g. modular/index.html) from index.html.

Each page loads the same css/js as the main site but opens straight to one
pump, with no facility picker and no "Change facility" button, so a single
link can be shared (for example for simulation onboarding):
    https://laurajobe.github.io/IV-INFUSION-PUMPS/modular/

Usage: python3 tools/build_pump_pages.py          (write the pages)
       python3 tools/build_pump_pages.py --check  (fail if a page is out of date)
Run it after changing index.html.
"""
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent

# folder -> (device id, opening mode, page title, short home-screen name)
# modular/ is the simulation-orientation page: modular pump only, opening on
# the guided orientation tasks. The main site (index.html) is the clinical
# onboarding version with the facility picker.
PAGES = {
    "modular": ("mod", "orient", "IV Pump Orientation", "Pump Orientation"),
}


def page_html(device, mode, title, short):
    html = (root / "index.html").read_text()
    # Local files live one folder up.
    html = re.sub(r'(href|src)="(?!https?:|#|data:|\.\./)([^"]+)"', r'\1="../\2"', html)
    # This page's own manifest, so "Add to Home Screen" reopens this pump.
    html = html.replace('href="../manifest.webmanifest"', 'href="manifest.webmanifest"', 1)
    html = re.sub(r"<title>.*?</title>", f"<title>{title}</title>", html, count=1)
    html = re.sub(r'(name="apple-mobile-web-app-title" content=")[^"]*"', rf'\g<1>{short}"', html, count=1)
    marker = '<script src="../js/library.js"></script>'
    assert marker in html, "index.html no longer loads js/library.js"
    lock = f'<script>window.IVP_CONFIG = {{ device: "{device}", mode: "{mode}" }};</script>\n'
    html = html.replace(marker, lock + marker, 1)
    note = "<!-- Generated by tools/build_pump_pages.py from index.html: edit index.html, then re-run the script. -->\n"
    return html.replace("<!doctype html>\n", "<!doctype html>\n" + note, 1)


def manifest(title, short):
    m = json.loads((root / "manifest.webmanifest").read_text())
    m.update({"id": "./", "name": title, "short_name": short, "start_url": "./", "scope": "./"})
    for icon in m.get("icons", []):
        icon["src"] = "../" + icon["src"]
    return json.dumps(m, indent=2) + "\n"


check = "--check" in sys.argv
stale = []
for folder, (device, mode, title, short) in PAGES.items():
    for name, text in (("index.html", page_html(device, mode, title, short)), ("manifest.webmanifest", manifest(title, short))):
        path = root / folder / name
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(f"{folder}/{name}")
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(text)
            print(f"wrote {folder}/{name}")
if stale:
    sys.exit("out of date (run python3 tools/build_pump_pages.py): " + ", ".join(stale))
